"""
NetCDF schedule file reader for station plan forecasting.

This module provides functions to read cruise schedule data from NetCDF files
generated by the cruiseplan schedule command.
"""

import logging
from datetime import datetime, timedelta
from pathlib import Path

import numpy as np
import pandas as pd
import xarray as xr

from cruiseplan.timeline.record import KIND_CATEGORY, ActivityRecord, kind_of

logger = logging.getLogger(__name__)


# Minutes per unit of a duration variable, by its units attribute
_MINUTES_PER_UNIT = {
    "minute": 1.0,
    "minutes": 1.0,
    "min": 1.0,
    "hour": 60.0,
    "hours": 60.0,
    "h": 60.0,
    "second": 1.0 / 60.0,
    "seconds": 1.0 / 60.0,
    "s": 1.0 / 60.0,
    "day": 1440.0,
    "days": 1440.0,
    "d": 1440.0,
}

# Target unit and factor per unit of the other physical variables, by their
# units attribute: (variables, unit written, {unit read: factor})
_CONVERSIONS = (
    (
        ("distance",),
        "nautical_mile",
        {
            "nautical_mile": 1.0,
            "nautical_miles": 1.0,
            "nmi": 1.0,
            "km": 1.0 / 1.852,
            "kilometer": 1.0 / 1.852,
            "m": 1.0 / 1852.0,
        },
    ),
    (
        ("vessel_speed",),
        "knot",
        {"knot": 1.0, "knots": 1.0, "kt": 1.0, "m s-1": 1.0 / 0.514444},
    ),
    (
        ("water_depth", "operation_depth"),
        "m",
        {"m": 1.0, "meter": 1.0, "metre": 1.0, "meters": 1.0, "km": 1000.0},
    ),
)


def _convert(
    schedule: xr.Dataset,
    var: str,
    target: str,
    factors: dict[str, float],
    filepath: Path | str,
) -> xr.Dataset:
    """Convert *var* to *target* units using its units attribute."""
    units = schedule[var].attrs.get("units")
    rewrite = "write the schedule again with `cruiseplan schedule`"
    if units is None:
        raise ValueError(
            f"{filepath}: variable '{var}' has no units attribute; {rewrite}"
        )
    factor = factors.get(str(units).strip())
    if factor is None:
        raise ValueError(
            f"{filepath}: variable '{var}' has unknown units '{units}'; {rewrite}"
        )
    if factor != 1.0 or units != target:
        attrs = {**schedule[var].attrs, "units": target}
        schedule = schedule.assign({var: (schedule[var] * factor).assign_attrs(attrs)})
    return schedule


def _to_minutes(schedule: xr.Dataset, var: str, filepath: Path | str) -> xr.Dataset:
    """Convert a duration variable to minutes using its units attribute."""
    return _convert(schedule, var, "minute", _MINUTES_PER_UNIT, filepath)


def to_current_format(
    schedule: xr.Dataset, filepath: Path | str = "schedule"
) -> xr.Dataset:
    """
    Return a schedule in the current layout: durations in minutes, ``distance``.

    Files written by cruiseplan 0.5.0 store durations in hours and the
    activity distance as ``dist_nm``; they are converted here (read support
    until 0.7.0). Durations, distance, speed and depths are converted by
    their ``units`` attribute, never assumed; times opened without decoding
    are decoded. A dataset already in the current layout is returned
    unchanged.

    Parameters
    ----------
    schedule : xr.Dataset
        Schedule dataset as opened from a file.
    filepath : Path or str, optional
        File name used in messages.

    Returns
    -------
    xr.Dataset
        The dataset in the current layout.

    Raises
    ------
    ValueError
        If a duration variable has no units attribute or unknown units.
    """
    if "dist_nm" in schedule.variables and "distance" not in schedule.variables:
        schedule = schedule.rename({"dist_nm": "distance"})
        logger.info(
            f"{filepath}: schedule written by cruiseplan 0.5.0 (dist_nm, durations "
            "in hours); read support ends in 0.7.0"
        )
    if not np.issubdtype(schedule["time"].dtype, np.datetime64):
        # Opened without decoding times (decode_times=False): decode by units
        units = str(schedule["time"].attrs.get("units", ""))
        if " since " not in units:
            raise ValueError(
                f"{filepath}: time has units '{units}', not '<unit> since <date>'"
            )
        schedule = xr.decode_cf(schedule)
    for var in ("duration", "planned_duration"):
        if var in schedule.variables:
            schedule = _to_minutes(schedule, var, filepath)
    for names, target, factors in _CONVERSIONS:
        for var in names:
            if var in schedule.variables:
                schedule = _convert(schedule, var, target, factors, filepath)
    if "planned_duration" not in schedule.variables:
        schedule = schedule.assign(planned_duration=schedule["duration"])
    return schedule


def duration_hours(schedule: xr.Dataset, index: int) -> float:
    """
    Return the duration of row *index* in hours.

    Parameters
    ----------
    schedule : xr.Dataset
        Schedule dataset from :func:`read_schedule` (durations in minutes).
    index : int
        Row index.

    Returns
    -------
    float
        Duration in hours.
    """
    return float(schedule.duration[index].values) / 60.0


def read_schedule(filepath: str | Path) -> xr.Dataset:
    """
    Read NetCDF schedule file and return dataset.

    Parameters
    ----------
    filepath : str or Path
        Path to NetCDF schedule file (e.g., 'MSM142_leg_2_schedule.nc')

    Returns
    -------
    xr.Dataset
        Dataset containing schedule variables:
        - time: Relative timestamps from cruise start
        - name: Activity names (stations, transits, etc.)
        - category: Activity types ('point_operation', 'transit', 'other')
        - type: Specific operation type (CTD, mooring, etc.)
        - action: Specific action (deployment, recovery, profile, etc.)
        - duration, planned_duration: Activity duration in minutes (files
          written by 0.5.0, in hours, are converted on reading)
        - latitude, longitude: Position coordinates
        - comment: Descriptive text

    Raises
    ------
    FileNotFoundError
        If the schedule file doesn't exist
    ValueError
        If the file is not a valid NetCDF file or missing required variables

    Examples
    --------
    >>> schedule = read_schedule("MSM142_leg_2_schedule.nc")
    >>> print(schedule.name.values)  # Show activity names
    """
    filepath = Path(filepath)

    if not filepath.exists():
        raise FileNotFoundError(f"Schedule file not found: {filepath}")

    if not filepath.suffix == ".nc":
        raise ValueError(f"Schedule file must be NetCDF format (.nc): {filepath}")

    try:
        logger.info(f"Reading schedule from: {filepath}")
        schedule = xr.open_dataset(filepath)

        # Validate required variables exist
        required_vars = [
            "time",
            "name",
            "category",
            "duration",
            "latitude",
            "longitude",
        ]
        missing_vars = [var for var in required_vars if var not in schedule.variables]

        if missing_vars:
            raise ValueError(
                f"Schedule file missing required variables: {missing_vars}"
            )

        schedule = to_current_format(schedule, filepath)
        logger.info(
            f"Successfully loaded schedule with {len(schedule.time)} activities"
        )
        return schedule

    except Exception as e:
        if isinstance(e, (FileNotFoundError, ValueError)):
            raise
        raise ValueError(f"Error reading NetCDF schedule file {filepath}: {e}") from e


def _number(
    schedule: xr.Dataset, var: str, i: int, default: float | None
) -> float | None:
    """Value of *var* at row *i* as float; None for NaN, *default* if absent."""
    if var not in schedule.variables:
        return default
    number = float(schedule[var][i].values)
    return None if np.isnan(number) else number


def _float(
    schedule: xr.Dataset, var: str, i: int, default: float | xr.DataArray
) -> float:
    """Value of *var* at row *i* as float (NaN kept); *default* if absent."""
    if var in schedule.variables:
        return float(schedule[var][i].values)
    if isinstance(default, xr.DataArray):
        return float(default[i].values)
    return float(default)


def _text(schedule: xr.Dataset, var: str, i: int, default: str | None) -> str | None:
    """Value of *var* at row *i* as text; *default* if absent, empty or missing."""
    if var not in schedule.variables:
        return default
    text = str(schedule[var][i].values)
    return default if text in {"", "nan", "None"} else text


# Categories that name one kind. point_operation covers several kinds and
# other covers buffers and waypoints; for those the type decides.
_KIND_BY_CATEGORY = {
    category: kind
    for kind, category in KIND_CATEGORY.items()
    if list(KIND_CATEGORY.values()).count(category) == 1 and category != "other"
}


def stored_kind(schedule: xr.Dataset, index: int) -> str:
    """
    Return the record kind of row *index* of a schedule dataset.

    Uses the stored ``operation_class`` and ``type``; files without
    ``operation_class`` fall back to ``category``.

    Parameters
    ----------
    schedule : xr.Dataset
        Schedule dataset from :func:`read_schedule`.
    index : int
        Row index.

    Returns
    -------
    str
        One of :data:`cruiseplan.timeline.record.KINDS`.
    """

    def text(var: str) -> str:
        if var not in schedule.variables:
            return ""
        return str(schedule[var][index].values).strip()

    op_type = text("type")
    try:
        return kind_of(text("operation_class"), op_type)
    except ValueError:
        pass
    category = text("category")
    if category in _KIND_BY_CATEGORY:
        return _KIND_BY_CATEGORY[category]
    if op_type == "buffer":
        return "buffer"
    return kind_of("PointOperation", op_type)


def netcdf_to_activity_records(schedule: xr.Dataset) -> list[ActivityRecord]:
    """
    Convert NetCDF schedule dataset to ActivityRecord objects.

    This function performs the inverse of the NetCDF generation, reconstructing
    ActivityRecord objects from NetCDF variables for complete roundtrip fidelity.

    Parameters
    ----------
    schedule : xr.Dataset
        NetCDF schedule dataset

    Returns
    -------
    List[ActivityRecord]
        List of ActivityRecord objects reconstructed from NetCDF data

    Examples
    --------
    >>> schedule = read_schedule("schedule.nc")
    >>> activity_records = netcdf_to_activity_records(schedule)
    >>> for record in activity_records:
    ...     print(f"{record.label}: {record.activity}")
    """
    schedule = to_current_format(schedule)
    activity_records = []
    if "vessel_speed" not in schedule.variables:
        logger.warning("Schedule has no vessel_speed variable; record speeds are NaN")

    # Get the number of observations
    n_obs = len(schedule.time)

    for i in range(n_obs):
        # Convert NetCDF time values back to datetime objects
        # Handle both numpy datetime64 and float values
        time_value = schedule.time[i].values
        if np.issubdtype(type(time_value), np.datetime64):
            # Already a datetime64, convert to datetime
            start_time = pd.to_datetime(time_value).floor("us").to_pydatetime()
        elif isinstance(time_value, np.integer):
            # Handle nanosecond timestamps
            start_time = pd.to_datetime(time_value).floor("us").to_pydatetime()
        else:
            # Convert days since epoch to datetime
            start_time_days = float(time_value)
            start_time = datetime(1970, 1, 1) + timedelta(days=start_time_days)

        # Handle end_time if present, otherwise calculate from duration
        if "end_time" in schedule.variables:
            end_time_value = schedule.end_time[i].values
            if np.issubdtype(type(end_time_value), np.datetime64) or isinstance(
                end_time_value, np.integer
            ):
                end_time = pd.to_datetime(end_time_value).floor("us").to_pydatetime()
            elif not np.isnan(float(end_time_value)):
                end_time_days = float(end_time_value)
                end_time = datetime(1970, 1, 1) + timedelta(days=end_time_days)
            else:
                end_time = start_time + timedelta(
                    minutes=float(schedule.duration[i].values)
                )
        else:
            end_time = start_time + timedelta(
                minutes=float(schedule.duration[i].values)
            )

        duration_minutes = float(schedule.duration[i].values)
        planned_minutes = float(schedule.planned_duration[i].values)
        comment = _text(schedule, "comment", i, "")
        activity_records.append(
            ActivityRecord(
                kind=stored_kind(schedule, i),
                activity=_text(
                    schedule, "activity", i, _text(schedule, "category", i, "")
                ),
                label=str(schedule.name[i].values),
                entry_lat=float(schedule.latitude[i].values),
                entry_lon=float(schedule.longitude[i].values),
                exit_lat=_float(schedule, "exit_latitude", i, schedule.latitude),
                exit_lon=_float(schedule, "exit_longitude", i, schedule.longitude),
                start_time=start_time,
                end_time=end_time,
                duration_minutes=duration_minutes,
                planned_duration_minutes=planned_minutes,
                dist_nm=_number(schedule, "distance", i, 0.0) or 0.0,
                transit_dist_nm=_number(schedule, "distance_to_next", i, 0.0) or 0.0,
                vessel_speed_kt=_float(schedule, "vessel_speed", i, np.nan),
                leg_name=_text(schedule, "leg_assignment", i, "unknown"),
                op_type=_text(schedule, "type", i, _text(schedule, "category", i, "")),
                operation_class=_text(schedule, "operation_class", i, "unknown"),
                action=_text(schedule, "action", i, None),
                operation_depth_m=_number(schedule, "operation_depth", i, None),
                water_depth_m=_number(schedule, "water_depth", i, None),
                delay_start_minutes=_number(schedule, "delay_start", i, None),
                duration_is_fill=(
                    bool(int(schedule.duration_fill_flag[i].values))
                    if "duration_fill_flag" in schedule.variables
                    else False
                ),
                comment=comment,
            )
        )

    logger.info(
        f"Converted {len(activity_records)} NetCDF observations to ActivityRecord objects"
    )
    return activity_records
